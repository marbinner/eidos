/// What the table has for `ch`, if it is in it.
pub(super) fn known(ch: char, mono: bool) -> Option<[f32; 2]> {
    let i = (ch as usize).checked_sub(32)?;
    KNOWN.get(i).map(|both| both[mono as usize])
}
